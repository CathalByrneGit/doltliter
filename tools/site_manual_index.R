#!/usr/bin/env Rscript
# Regenerate site/manual.Rmd and the redirect stubs under site/reference/.
#
#   Rscript tools/site_manual_index.R
#
# litedown's pkg_manual() writes one page per help topic and its own
# alphabetical index. This adds the grouped index the pkgdown reference page
# used to have, which is the only part of that configuration worth keeping by
# hand. Run it after adding or renaming an exported function: the groups below
# are the source of truth, and the script stops if a topic in man/ is missing
# from them, so a new function cannot quietly drop out of the index.

if (!file.exists("DESCRIPTION")) stop("run this from the package root")

# Groups carried over from the old _pkgdown.yml reference sections. Entries are
# help topics -- an Rd file name or any of its aliases.
groups <- list(
  list("Connecting",
       "Opening a database, optionally straight onto a branch. `dbConnect()` takes the DoltLite-specific `branch`, `bigint` and `busy_timeout` arguments alongside the usual DBI ones.",
       c("Doltlite", "dbConnect,DoltliteDriver-method", "DOLTLITE_RO")),
  list("DBI classes and methods",
       "The ordinary DBI surface. These behave as they would for any SQLite database, with the documented exceptions around clustered primary keys and transactions.",
       c("DoltliteDriver-class", "DoltliteConnection-class", "DoltliteResult-class",
         "dbWriteTable,DoltliteConnection,character,data.frame-method",
         "dbDataType,DoltliteDriver-method", "doltliter-transactions")),
  list("Configuring and committing",
       "The commit loop. Note that `dolt_commit()` is the *Dolt* sense of commit -- it writes to the version history -- and is unrelated to `DBI::dbCommit()`.",
       c("dolt_config", "dolt_add", "dolt_commit", "dolt_status", "dolt_reset",
         "dolt_revert", "dolt_cherry_pick")),
  list("Branches, merging and conflicts",
       "Each connection selects its own branch. Conflicts exist only inside the transaction that produced them, so a merge you expect to conflict belongs in one.",
       c("dolt_branch", "dolt_checkout", "dolt_active_branch", "dolt_merge",
         "dolt_merge_base", "dolt_merge_status", "dolt_rebase", "dolt_tag",
         "dolt_conflicts", "dolt_constraint_violations")),
  list("History, diffs and time travel",
       "Reading the past: what changed, when, and who changed it.",
       c("dolt_log", "dolt_diff", "dolt_table_diff", "dolt_diff_stat", "dolt_patch",
         "dolt_history", "dolt_at", "dolt_blame", "dolt_workspace", "dolt_schemas")),
  list("Remotes",
       "Pushing and pulling between databases, over the filesystem or HTTP.",
       c("dolt_remote", "dolt_push", "dolt_pull", "dolt_clone", "dolt_creds")),
  list("Interactive",
       "A Shiny gadget and RStudio addin over a connection you already have open.",
       c("dolt_pane")),
  list("Introspection and maintenance",
       "Content hashes, versions and housekeeping.",
       c("dolt_hashof", "dolt_version", "doltlite_engine", "dolt_gc",
         "dolt_verify_constraints")),
  list("Calling anything else",
       "The two escape hatches for DoltLite functions this package does not wrap, with arguments bound as parameters rather than pasted into SQL.",
       c("dolt_scalar", "dolt_table")),
  list("Re-exported from DBI", "", c("reexports"))
)

rd <- list.files("man", pattern = "\\.Rd$")
stem <- sub("\\.Rd$", "", rd)

# alias -> Rd stem, so method selectors such as dbConnect,DoltliteDriver-method
# resolve to the file that documents them.
alias <- list()
internal <- character()
for (i in seq_along(rd)) {
  txt <- readLines(file.path("man", rd[i]), warn = FALSE)
  for (a in sub(".*\\\\alias\\{(.*)\\}.*", "\\1", grep("\\\\alias\\{", txt, value = TRUE)))
    alias[[a]] <- stem[i]
  if (any(grepl("\\\\keyword\\{internal\\}", txt))) internal <- c(internal, stem[i])
}
for (s in stem) alias[[s]] <- s

listed <- unlist(lapply(groups, `[[`, 3))
unresolved <- setdiff(listed, names(alias))
if (length(unresolved))
  stop("topics in the groups with no help page: ", paste(unresolved, collapse = ", "))

missing <- setdiff(stem, unique(unlist(alias[listed])))
if (length(missing))
  stop("help pages missing from the groups in this script: ",
       paste(missing, collapse = ", "),
       "\nAdd them to `groups` so they appear in the grouped index.")

# litedown writes no page for a topic marked \keyword{internal} and leaves it
# out of its own index, so linking one here would point at a file that is
# never generated.
page <- function(entry) paste0(xfun::alnum_id(alias[[entry]]), ".html")
label <- function(entry) {
  if (grepl(",", entry)) paste0(sub(",.*", "", entry), "()")
  else if (grepl("-class$|-transactions$|^DOLTLITE_RO$|^reexports$", entry)) entry
  else paste0(entry, "()")
}

out <- c("---", "title: Help pages", "---", "",
         "<!-- Generated by tools/site_manual_index.R. Edit the groups there. -->", "",
         "Every help page in the package. The grouping below is the one the reference",
         "index used to have; an alphabetical list of the same pages follows.", "")
skipped <- character()
for (g in groups) {
  keep <- !vapply(g[[3]], function(e) alias[[e]] %in% internal, logical(1))
  skipped <- c(skipped, g[[3]][!keep])
  if (!any(keep)) next
  out <- c(out, trimws(paste0("**", g[[1]], ".** ", g[[2]])), "",
           paste(sprintf("[%s](manual/%s)", vapply(g[[3]][keep], label, ""),
                         vapply(g[[3]][keep], page, "")), collapse = ", "), "")
}
out <- c(out, "", "```{r}", "#| echo: false", "litedown::pkg_manual()", "```", "")
writeLines(out, "site/manual.Rmd")
cat("wrote site/manual.Rmd\n")
if (length(skipped))
  cat("omitted (\\keyword{internal}, litedown writes no page):",
      paste(skipped, collapse = ", "), "\n")

# Redirect stubs for the old pkgdown URLs. The skill's make_redirects.py aims
# at ../manual.html#sec:man-<name>, which is the single-page manual layout;
# this site builds a paged manual, so each stub points at the topic's page.
dir.create("site/reference", showWarnings = FALSE, recursive = TRUE)
stub <- function(to) sprintf(
'<!DOCTYPE html>
<html><head><meta charset="utf-8">
<title>Moved</title>
<link rel="canonical" href="%s">
<meta http-equiv="refresh" content="0; url=%s">
</head><body><p>This page has moved to <a href="%s">%s</a>.</p>
<script>location.replace("%s");</script>
</body></html>
', to, to, to, to, to)
for (i in seq_along(rd)) {
  to <- if (stem[i] %in% internal) "../manual.html" else paste0("../manual/", xfun::alnum_id(stem[i]), ".html")
  writeLines(stub(to), file.path("site/reference", paste0(stem[i], ".html")))
}
cat("wrote", length(rd), "redirect stubs in site/reference/\n")
